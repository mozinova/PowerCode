// Lists every member of the `vscode` API namespaces (window, workspace, ...) from
// @types/vscode, so the extension host can fill in what it does not implement
// (extensions must never find `undefined` where VS Code has a member).
//
//   node scripts/gen-vscode-surface.mjs   (after updating @types/vscode)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dts = readFileSync(join(root, "node_modules", "@types", "vscode", "index.d.ts"), "utf8");
const { version } = JSON.parse(readFileSync(join(root, "node_modules", "@types", "vscode", "package.json"), "utf8"));

// Comments out, so braces and keywords in docs do not count.
const code = dts.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");

/** The text of each top-level `export namespace x { ... }` inside `declare module 'vscode'`. */
function namespaces(source) {
  const result = {};
  // `export` is optional: inside `declare module` everything is exported (e.g. `namespace comments`).
  const pattern = /(?:export )?namespace (\w+) \{/g;
  for (const match of source.matchAll(pattern)) {
    // Only namespaces directly in the module (depth 1).
    let depth = 0;
    for (let i = 0; i < match.index; i++) {
      if (source[i] === "{") depth++;
      else if (source[i] === "}") depth--;
    }
    if (depth !== 1) continue;
    let level = 0;
    let end = match.index + match[0].length - 1;
    for (; end < source.length; end++) {
      if (source[end] === "{") level++;
      else if (source[end] === "}" && --level === 0) break;
    }
    result[match[1]] = source.slice(match.index + match[0].length, end);
  }
  return result;
}

/** Statements at the namespace's own level (not inside nested types). */
function statements(body) {
  const out = [];
  let depth = 0;
  let current = "";
  let previous = "";
  for (const ch of body) {
    if (ch === "{" || ch === "(" || ch === "<" || ch === "[") depth++;
    // The `>` of an arrow (`=>`) closes nothing.
    if (ch === "}" || ch === ")" || (ch === ">" && previous !== "=") || ch === "]") depth--;
    previous = ch;
    current += ch;
    if (ch === ";" && depth === 0) {
      out.push(current.trim());
      current = "";
    }
  }
  return out;
}

function kindOf(statement) {
  const fn = /^export function (\w+)[\s\S]*\)\s*:\s*([\s\S]+);$/.exec(statement);
  if (fn) {
    const returns = fn[2].trim();
    if (/^Thenable</.test(returns)) return [fn[1], "promise"];
    if (/^Disposable\b/.test(returns)) return [fn[1], "disposable"];
    return [fn[1], "value"];
  }
  const prop = /^export (?:const|let) (\w+)\s*:\s*([\s\S]+);$/.exec(statement);
  if (prop) {
    const type = prop[2].trim();
    if (/^Event</.test(type)) return [prop[1], "event"];
    if (/\[\]$|^readonly .*\[\]$|^ReadonlyArray</.test(type)) return [prop[1], "array"];
    return [prop[1], "property"];
  }
  return null;
}

/** Values the module exports at its top level (classes, enums, constants), not types. */
function topLevelValues(source) {
  const names = new Set();
  for (const match of source.matchAll(/(?:export )?(?:class|enum|const|let|function) (\w+)/g)) {
    let depth = 0;
    for (let i = 0; i < match.index; i++) {
      if (source[i] === "{") depth++;
      else if (source[i] === "}") depth--;
    }
    if (depth === 1) names.add(match[1]);
  }
  return [...names].sort();
}

const topLevel = topLevelValues(code);

const surface = {};
for (const [name, body] of Object.entries(namespaces(code))) {
  const members = {};
  for (const statement of statements(body)) {
    const entry = kindOf(statement);
    if (entry) members[entry[0]] = entry[1];
  }
  surface[name] = Object.fromEntries(Object.entries(members).sort(([a], [b]) => a.localeCompare(b)));
}

const out = join(root, "ext-host", "src", "surface.ts");
writeFileSync(
  out,
  `//! Generated by scripts/gen-vscode-surface.mjs from @types/vscode ${version}: every member
//! of the API's namespaces, by kind, for filling in what PowerCode does not implement.

export type MemberKind = "event" | "promise" | "disposable" | "value" | "array" | "property";

export const VSCODE_TYPES_VERSION = ${JSON.stringify(version)};

export const SURFACE: Record<string, Record<string, MemberKind>> = ${JSON.stringify(surface, null, 2)};

/** Classes, enums and constants at the module's top level. */
export const TOP_LEVEL: string[] = ${JSON.stringify(topLevel, null, 2)};
`,
);
const counts = Object.entries(surface).map(([n, m]) => `${n} ${Object.keys(m).length}`);
console.log(`@types/vscode ${version}: ${counts.join(", ")}; ${topLevel.length} top-level values`);
